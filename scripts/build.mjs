// Regenerates data/bank.js and data/solutions.js from their JSON sources.
// Run after editing data/bank.json or data/solutions/*.json:  node scripts/build.mjs
import fs from 'node:fs';
const bank = JSON.parse(fs.readFileSync('data/bank.json', 'utf8'));
const all = bank.sets.flatMap((s) => s.questions);
for (const st of ['clean', 'approximate', 'partial', 'missing']) bank.totals[st] = all.filter((q) => q.status === st).length;
fs.writeFileSync('data/bank.json', JSON.stringify(bank, null, 1));
fs.writeFileSync('data/bank.js', '// Generated by scripts/build.mjs from data/bank.json – do not edit by hand.\nwindow.BANK=' + JSON.stringify(bank) + ';\n');
const sol = {};
if (fs.existsSync('data/solutions')) {
  for (const f of fs.readdirSync('data/solutions').filter((f) => f.endsWith('.json')).sort()) {
    Object.assign(sol, JSON.parse(fs.readFileSync('data/solutions/' + f, 'utf8')));
  }
}
fs.writeFileSync('data/solutions.js', '// Generated by scripts/build.mjs from data/solutions/*.json – do not edit by hand.\nwindow.SOLUTIONS=' + JSON.stringify(sol) + ';\n');
console.log('bank', bank.totals, 'solutions', Object.keys(sol).length);
