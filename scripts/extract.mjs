// One-off migration: reads the legacy per-set pages (sets/NN.html) and the answer
// key embedded in the legacy index.html, and writes the unified question bank to
// data/bank.js (window.BANK) + data/bank.json. Every one of the 40 sets x 10 slots
// is present; slots the video never captured are kept with status "missing".
//
// Usage: node scripts/extract.mjs   (run from the repo root, against the legacy files)
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const legacyIndex = fs.readFileSync(path.join(root, process.argv[2] || 'index.html'), 'utf8');
const m = legacyIndex.match(/window\.KAMUTI=(\{.*?\});<\/script>/s);
if (!m) throw new Error('answer key not found in legacy index.html');
const KAMUTI = JSON.parse(m[1]);
const setsDir = path.join(root, process.argv[3] || 'sets');

// Return [start, end) of the <div ...> element that opens at `from` (balanced on div tags).
function divEnd(html, from) {
  const re = /<\/?div\b[^>]*>/g;
  re.lastIndex = from;
  let depth = 0, t;
  while ((t = re.exec(html))) {
    depth += t[0][1] === '/' ? -1 : 1;
    if (depth === 0) return re.lastIndex;
  }
  throw new Error('unbalanced div at ' + from);
}
const inner = (el) => el.slice(el.indexOf('>') + 1, el.lastIndexOf('</'));
const textOf = (h) => h.replace(/<[^>]+>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/\s+/g, ' ').trim();

const sets = [];
for (let s = 1; s <= 40; s++) {
  const file = path.join(setsDir, String(s).padStart(2, '0') + '.html');
  const key = KAMUTI.key[s] || null;
  const set = { set: s, page: fs.existsSync(file), hasKey: !!key, gaps: [], questions: [] };
  const byN = {};
  if (set.page) {
    const html = fs.readFileSync(file, 'utf8');
    // gap notices (pages skipped / blurry in the video)
    for (const g of html.matchAll(/<div class="gap">/g)) {
      const el = html.slice(g.index, divEnd(html, g.index));
      const nextQ = html.slice(g.index).match(/id="q\d+-(\d+)"/);
      set.gaps.push({ beforeQ: nextQ ? +nextQ[1] : null, html: inner(el).replace(/^<p>|<\/p>$/g, ''), text: textOf(el) });
    }
    for (const q of html.matchAll(/<div class="q" id="q(\d+)-(\d+)">/g)) {
      const n = +q[2];
      const el = html.slice(q.index, divEnd(html, q.index));
      const qbAt = el.indexOf('<div class="qb">');
      const qb = inner(el.slice(qbAt, divEnd(el, qbAt)));
      let rest = qb;
      // notes
      const notes = [];
      for (;;) {
        const i = rest.indexOf('<div class="note">');
        if (i < 0) break;
        const e = divEnd(rest, i);
        notes.push(inner(rest.slice(i, e)).replace(/^<p>|<\/p>$/g, ''));
        rest = rest.slice(0, i) + rest.slice(e);
      }
      // figure
      let figure = null;
      const f = rest.match(/<figure class="fig( wide)?"(?: style="--w:([\d.]+%)")?><img src="\.\.\/(fig\/[^"]+)"[^>]*><\/figure>/);
      if (f) { figure = { src: f[3], width: f[2] || null, wide: !!f[1] }; rest = rest.replace(f[0], ''); }
      // options
      let options = null;
      const o = rest.match(/<ol class="opts">[\s\S]*?<\/ol>/);
      if (o) {
        options = [...o[0].matchAll(/<span class="ot">([\s\S]*?)<\/span><\/button>/g)].map((x) => x[1]);
        rest = rest.replace(o[0], '');
      }
      const stem = rest.trim();
      const all = qb;
      const warns = [...all.matchAll(/<span class="warn" title="([^"]*)">⚠<\/span>/g)].map((x) => x[1] || 'נקרא בקירוב');
      const unreadable = /לא קריא|מטושטש לחלוטין|\(טקסט מטושטש\)/.test(textOf(all));
      const status = !options || options.length !== 4 || unreadable ? 'partial' : warns.length ? 'approximate' : 'clean';
      byN[n] = {
        id: `${s}-${n}`, set: s, n, status,
        answer: key ? key[n - 1] : null,
        stem, options, figure, notes,
        flags: [...new Set(warns)],
        text: textOf(stem + ' ' + (options || []).join(' ')),
      };
    }
  }
  for (let n = 1; n <= 10; n++) {
    set.questions.push(byN[n] || {
      id: `${s}-${n}`, set: s, n, status: 'missing',
      answer: key ? key[n - 1] : null,
      stem: null, options: null, figure: null, notes: [], flags: [], text: '',
    });
  }
  sets.push(set);
}

const all = sets.flatMap((s) => s.questions);
const count = (st) => all.filter((q) => q.status === st).length;
const bank = {
  source: 'כמותי – מקבצים מעורבים',
  generated: new Date().toISOString().slice(0, 10),
  totals: { slots: all.length, clean: count('clean'), approximate: count('approximate'), partial: count('partial'), missing: count('missing') },
  sets,
};
fs.mkdirSync(path.join(root, 'data'), { recursive: true });
fs.writeFileSync(path.join(root, 'data/bank.json'), JSON.stringify(bank, null, 1));
fs.writeFileSync(path.join(root, 'data/bank.js'), '// Generated by scripts/extract.mjs – the unified question bank.\nwindow.BANK=' + JSON.stringify(bank) + ';\n');
console.log(bank.totals);
for (const s of sets) {
  const miss = s.questions.filter((q) => q.status === 'missing').map((q) => q.n);
  const part = s.questions.filter((q) => q.status === 'partial').map((q) => q.n);
  const appr = s.questions.filter((q) => q.status === 'approximate').map((q) => q.n);
  console.log(`set ${s.set}\tkey:${s.hasKey ? 'y' : 'n'}\tmissing:[${miss}]\tpartial:[${part}]\tapprox:[${appr}]`);
}
