# ---------------------------------------------------------------- 6  (18-6)
def fig6():
    f = Fig(440, 300)
    c = (220, 150)
    hw, hh = 190, 120           # half diagonals
    A, B, C, D = (c[0], c[1] - hh), (c[0] + hw, c[1]), (c[0], c[1] + hh), (c[0] - hw, c[1])
    side = math.hypot(hw, hh)
    r = hw * hh / side
    def foot(P, Q_):
        ux, uy = (Q_[0] - P[0]) / side, (Q_[1] - P[1]) / side
        t = (c[0] - P[0]) * ux + (c[1] - P[1]) * uy
        return (P[0] + t * ux, P[1] + t * uy)
    E, Fp = foot(A, B), foot(C, D)
    f.poly([A, B, C, D])
    f.circle(c, r)
    f.line(E, Fp)
    f.dot(E)
    f.dot(Fp)
    f.label(A, 'A', dy=-16)
    f.label(B, 'B', dx=16)
    f.label(C, 'C', dy=18)
    f.label(D, 'D', dx=-16)
    f.label(E, 'E', dx=12, dy=-14)
    f.label(Fp, 'F', dx=-12, dy=16)
    return f


