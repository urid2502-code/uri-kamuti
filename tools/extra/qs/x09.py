def fig4():
    import math as m
    f = Fig(460, 260)
    A0, B0, C0 = 40, 120, 20                     # a = 40°: A = a, B = 3a, C = ½a
    A = (34, 220)
    AC = 380
    C = (A[0] + AC, A[1])
    AB = AC * m.sin(m.radians(C0)) / m.sin(m.radians(B0))
    B = (A[0] + AB * m.cos(m.radians(A0)), A[1] - AB * m.sin(m.radians(A0)))
    f.poly([A, B, C])
    f.angle(A, B, C, r=40, text='a', tr=58)
    f.angle(B, A, C, r=26, text='3a', tr=44)
    f.label(A, 'A', dx=-16, dy=6)
    f.label(B, 'B', dy=-18)
    f.label(C, 'C', dx=16, dy=6)
    return f


def can(k):                       # ∢C = k · a with A = a, B = 3a obtuse
    a = 180 / (4 + k)
    return 30 < a < 45


