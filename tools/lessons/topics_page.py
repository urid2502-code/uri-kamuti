def ref(i):
    s, q = i.split('-')
    return '<a href="sets/%02d.html#q%s" title="מקבץ %s, שאלה %s">%s</a>' % (int(s), i, s, q, i)


def refs(ids):
    if not ids:
        return ''
    more = '<em>ועוד %d</em>' % (len(ids) - 6) if len(ids) > 6 else ''
    return '<div class="refs" aria-label="שאלות שמשתמשות בכלל">%s%s</div>' % (''.join(ref(i) for i in ids[:6]), more)


def main():
    p = os.path.join(REPO, 'data', 'lessons.json')
    L = json.load(open(p, encoding='utf-8'))
    old = {k: [r['ids'] for r in t['rules']] for k, t in L['topics'].items()}
    for k, rules in RULES.items():
        if 'ex' not in (L['topics'][k]['rules'] or [{}])[0]:      # first run: keep the questions of the original rules
            L['topics'][k]['rules'] = [{'t': t, 'ex': ex, 'ids': old[k][src]} for t, ex, src in rules]
        else:
            ids = [r['ids'] for r in L['topics'][k]['rules']]
            L['topics'][k]['rules'] = [{'t': t, 'ex': ex, 'ids': ids[n] if n < len(ids) else []} for n, (t, ex, _) in enumerate(rules)]
    json.dump(L, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

    arts = ''
    for k in ORDER:
        t = L['topics'][k]
        rules = ''.join('<li><p class="rl">%s</p><p class="ex"><b>דוגמה</b> %s</p>%s</li>'
                        % (explain.render_line(r['t']), explain.render_line(r['ex']), refs(r['ids'])) for r in t['rules'])
        pits = ''.join('<li>%s<span class="pt">%s</span></li>' % (ref(x['id']), explain.render_line(x['p'])) for x in t['pitfalls'])
        arts += ('<article class="topic" id="t-%s" data-topic="%s"><h3><span class="tp-ic" aria-hidden="true">%s</span>%s<small>%d שאלות</small></h3>'
                 '<p class="tp-meta">%d כללים · לחצו לפתיחה</p><p class="acc" data-acc="%s"></p>'
                 '<ul class="rules">%s</ul><details><summary>מוקשים נפוצים מהשאלות (%d)</summary><ul class="pits">%s</ul></details></article>\n'
                 % (k, k, ICON[k], t['name'], len(t['ids']), len(t['rules']), k, rules, len(t['pitfalls']), pits))
    sec = ('<section class="ls-sec" id="ls-topics" aria-labelledby="h-topics"><h2 id="h-topics">כללים לפי נושא</h2>'
           '<p>לחצו על נושא כדי לראות את הכללים שלו – כל כלל במשפט אחד, עם דוגמה ועם השאלות שבהן הוא מופיע.</p>'
           '<div class="ls-grid">\n%s</div></section>' % arts)

    page = os.path.join(REPO, 'lessons.html')
    s = open(page, encoding='utf-8').read()
    # the old topics section (and its tabs) becomes the new one
    s, n = re.subn(r'<section class="ls-sec"(?: style="margin-top:8px")? (?:id="ls-topics" )?aria-labelledby="h-(?:master|topics)">.*?</div></section>',
                   lambda m: sec, s, count=1, flags=re.S)
    assert n == 1
    s = re.sub(r'<header class="phead"><h1>נקודות ולקחים</h1>\s*<p>.*?</p>',
               '<header class="phead"><h1>נקודות ולקחים</h1>\n<p>הכללים, הטריקים והנוסחאות שחוזרים במבחן – בקיצור ועם דוגמה. הכול סגור: פותחים רק את מה שצריך.</p>', s, count=1, flags=re.S)
    nav = ('<nav class="ls-nav" aria-label="חלקי הדף"><a href="#ls-topics">📚 כללים לפי נושא</a><a href="#ls-tricks">🔁 דפוסים חוזרים</a>'
           '<a href="#ls-formulas">📐 נוסחאות גאומטריה</a><a href="#ls-formulas-alg">🔢 נוסחאות אלגברה</a><a href="#ls-sets">🗂 לקחים לפי מקבץ</a></nav>')
    s = re.sub(r'<nav class="(?:ls-nav|fm-nav)".*?</nav>', '', s, flags=re.S)
    i = s.index('<div class="pbody">') + len('<div class="pbody">')
    s = s[:i] + '\n' + nav + s[i:]
    s = s.replace('<section class="ls-sec" aria-labelledby="h-sets">', '<section class="ls-sec" id="ls-sets" aria-labelledby="h-sets">', 1)
    s = re.sub(r'(<details class="setl"[^>]*?) open', r'\1', s)
    open(page, 'w', encoding='utf-8').write(s)
    print('topics:', len(ORDER), 'rules:', sum(len(v) for v in RULES.values()))


if __name__ == '__main__':
    main()
