EXCLUDE = {'26-7': ['sector']}


def load_text():
    Q = {}
    lessons = {}
    for f in glob.glob(os.path.join(REPO, 'data', 'lessons', '[0-9]*.json')):
        lessons.update(json.load(open(f, encoding='utf-8')))
    for s in range(1, 41):
        E = json.load(open(os.path.join(REPO, 'data', 'explain', '%02d.json' % s), encoding='utf-8'))
        for n in range(1, 11):
            q = '%d-%d' % (s, n)
            e = E.get(q, {})
            Q[q] = (lessons.get(q, ''), ' '.join(e.get('pit', [])), ' '.join(e.get('steps', [])[:4]))
    return Q


def main():
    Q = load_text()
    out = {'tricks': {t: {'name': n, 'rule': r, 'ex': EX.get(t, ''), 'ids': []} for t, n, r, _ in TRICKS}, 'q': {}}
    for q, (lesson, pit, steps) in Q.items():
        tags = []
        # the takeaway and pitfall decide first; the explanation only fills a missing tag
        for text in (lesson + ' ' + pit, steps):
            for t, _n, _r, rx in TRICKS:
                if len(tags) == 2:
                    break
                if t not in tags and t not in EXCLUDE.get(q, []) and re.search(rx, text):
                    tags.append(t)
        for t in MANUAL.get(q, []):
            if len(tags) < 2 and t not in tags:
                tags.append(t)
        out['q'][q] = tags
        for t in tags:
            out['tricks'][t]['ids'].append(q)
    out['tricks'] = {t: v for t, v in out['tricks'].items() if len(v['ids']) >= 2}
    out['q'] = {q: [t for t in ts if t in out['tricks']] for q, ts in out['q'].items()}
    json.dump(out, open(os.path.join(REPO, 'data', 'lessons', 'tricks.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    for t, v in out['tricks'].items():
        print('%-10s %3d  %s' % (t, len(v['ids']), v['name']))
    print('untagged:', [q for q, ts in out['q'].items() if not ts])


if __name__ == '__main__':
    main()
